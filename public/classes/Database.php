<?php
require_once __DIR__ . '/../db.php';

/**
 * The only class that talks to PDO. Every query goes through a prepared
 * statement: SQL text and user values are always sent separately.
 */
class Database
{
    private PDO $pdo;

    public function __construct()
    {
        $this->pdo = db();   // provided connection (the only PostgreSQL-specific code is in db.php)
    }

    /** All matching rows, as associative arrays */
    public function fetchAll(string $sql, array $params = []): array
    {
        $statement = $this->pdo->prepare($sql);
        $statement->execute($params);
        return $statement->fetchAll();
    }

    /** The first matching row, or null if there is none */
    public function fetchOne(string $sql, array $params = []): ?array
    {
        $statement = $this->pdo->prepare($sql);
        $statement->execute($params);
        $row = $statement->fetch();
        return $row === false ? null : $row;
    }

    /** A single value, e.g. the result of COUNT(*) */
    public function fetchValue(string $sql, array $params = []): mixed
    {
        $statement = $this->pdo->prepare($sql);
        $statement->execute($params);
        return $statement->fetchColumn();
    }

    /** INSERT / UPDATE / DELETE; returns the number of affected rows */
    public function execute(string $sql, array $params = []): int
    {
        $statement = $this->pdo->prepare($sql);
        $statement->execute($params);
        return $statement->rowCount();
    }

    /** Id generated by the last INSERT (portable: no RETURNING clause needed) */
    public function lastInsertId(): int
    {
        return (int) $this->pdo->lastInsertId();
    }
}
